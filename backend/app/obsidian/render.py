"""Render the generated knowledge layer from the SQLite registry.

Everything here writes through a ScopedWriter bound to the generated folder,
so this module physically cannot touch the source mirror. Pages are fully
derived from the registry: deleting the generated folder and re-rendering
produces the same files.

Graph shape in Obsidian:
  source note  <-  entity page  ->  collection page
Entity pages link to the mirrored source notes that mention them, so two notes
that mention the same book become connected through the book's page without
any link being inserted into the notes themselves.
"""
from __future__ import annotations

import json
import logging
from collections import defaultdict
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from ..config import AppConfig
from ..entities.types import COLLECTION_TYPE, COLLECTIONS, ENTITY_TYPES, NOTE_TYPE
from ..intelligence.normalize import safe_filename
from ..intelligence.registry import collection_id
from ..storage.db import Database
from .writer import ScopedWriter, file_sha256, sha256_text

log = logging.getLogger(__name__)
REL_LABEL = {"mentions": "mentions", "about": "about", "references": "references", "related_to": "related to",
             "belongs_to": "belongs to"}
BANNER = ("> [!info] Generated by Knowledge Bridge\n"
          "> This page is rebuilt from the registry on every sync. Your own writing stays in your notes.\n")


@dataclass
class RenderStats:
    written: int = 0
    unchanged: int = 0
    removed: int = 0
    backed_up: int = 0


def _disp(s: str) -> str:
    return s.replace("|", "-").replace("[", "(").replace("]", ")").replace("\n", " ")


def _quote(s: str | None, n: int = 220) -> str:
    if not s:
        return ""
    s = " ".join(s.split())
    return " — “" + (s if len(s) <= n else s[:n].rstrip() + "…") + "”"


class Renderer:
    def __init__(self, db: Database, cfg: AppConfig):
        self.db = db
        self.cfg = cfg
        self.gen = cfg.generated_dir
        self.writer = ScopedWriter(cfg.generated_root())
        self.entities = {r["id"]: dict(r) for r in db.q("SELECT * FROM entities WHERE status='active'")}
        self.notes = {r["id"]: dict(r) for r in db.q("SELECT * FROM notes")}
        self.aliases: dict[str, list[str]] = defaultdict(list)
        for r in db.q("SELECT entity_id, alias, source FROM aliases ORDER BY source='canonical' DESC, alias"):
            if r["alias"] not in self.aliases[r["entity_id"]]:
                self.aliases[r["entity_id"]].append(r["alias"])
        self.rels = [dict(r) for r in db.q("SELECT * FROM relationships WHERE status='accepted' ORDER BY id")]
        self.out: dict[str, str] = {}  # path relative to generated root -> content
        self.paths: dict[str, str] = {}  # entity id -> path relative to generated root (no .md)

    # ---------------------------------------------------------------- links
    def link(self, eid: str) -> str:
        e = self.entities.get(eid)
        if not e:
            return ""
        if e["type"] == NOTE_TYPE:
            n = self.notes.get(e["note_id"])
            if not n or not n["mirror_path"]:
                return _disp(e["name"])
            target = n["mirror_path"][:-3] if n["mirror_path"].endswith(".md") else n["mirror_path"]
            suffix = " (removed from Apple Notes)" if n["status"] == "missing" else ""
            return f"[[{target}|{_disp(n['title'])}]]{suffix}"
        if eid in self.paths:
            return f"[[{self.gen}/{self.paths[eid]}|{_disp(e['name'])}]]"
        return _disp(e["name"])

    # ---------------------------------------------------------------- paths
    def assign_paths(self) -> None:
        for name in COLLECTIONS:
            self.paths[collection_id(name)] = f"Collections/{safe_filename(name)}"
        used: set[str] = set(p.casefold() for p in self.paths.values())
        personal = self.personal_notes()
        connected = self.connected_notes()
        ordered = sorted(self.entities.values(), key=lambda e: (e["created_at"], e["id"]))
        for e in ordered:
            t = ENTITY_TYPES.get(e["type"])
            if t:
                folder, label = f"Entities/{t.folder}", t.label
            elif e["type"] == NOTE_TYPE and e["id"] in personal:
                folder, label = "Entities/Personal Thinking", "Reflection"
            elif e["type"] == NOTE_TYPE and e["id"] in connected:
                folder, label = "Connections", "Note"
            else:
                continue
            stem = safe_filename(e["name"])
            prev = (e.get("page_path") or "").removeprefix(self.gen + "/").removesuffix(".md")
            cands = [f"{folder}/{stem}", f"{folder}/{stem} ({label})"] + [f"{folder}/{stem} ({label} {i})" for i in range(2, 50)]
            if prev in cands and prev.casefold() not in used:
                chosen = prev
            else:
                chosen = next(c for c in cands if c.casefold() not in used)
            used.add(chosen.casefold())
            self.paths[e["id"]] = chosen

    def personal_notes(self) -> set[str]:
        pid = collection_id("Personal Thinking")
        return {r["src_id"] for r in self.rels if r["type"] == "belongs_to" and r["tgt_id"] == pid}

    def connected_notes(self) -> set[str]:
        out = set()
        for r in self.rels:
            if r["type"] in ("references", "related_to"):
                a, b = self.entities.get(r["src_id"]), self.entities.get(r["tgt_id"])
                if a and b and a["type"] == NOTE_TYPE and b["type"] == NOTE_TYPE:
                    out |= {a["id"], b["id"]}
        return out

    # ---------------------------------------------------------------- pages
    def frontmatter(self, e: dict, kind: str) -> str:
        lines = ["---", f"kb_id: {json.dumps(e['id'])}", f"kb_type: {json.dumps(kind)}", "kb_generated: true"]
        aliases = [a for a in self.aliases.get(e["id"], []) if a != e["name"]]
        if aliases:
            lines.append("aliases:")
            lines += [f"  - {json.dumps(a, ensure_ascii=False)}" for a in aliases]
        lines.append("---")
        return "\n".join(lines) + "\n"

    def entity_page(self, e: dict) -> str:
        t = ENTITY_TYPES[e["type"]]
        eid = e["id"]
        parents = [r for r in self.rels if r["src_id"] == eid and r["type"] == "belongs_to"]
        children = [r for r in self.rels if r["tgt_id"] == eid and r["type"] == "belongs_to"
                    and self.entities.get(r["src_id"], {}).get("type") != NOTE_TYPE]
        mentions = [r for r in self.rels if r["tgt_id"] == eid and r["type"] in ("mentions", "about")
                    and self.entities.get(r["src_id"], {}).get("type") == NOTE_TYPE]
        related = [r for r in self.rels if r["type"] == "related_to" and eid in (r["src_id"], r["tgt_id"])]

        out = [self.frontmatter(e, e["type"]), f"# {e['name']}\n", BANNER]
        part_of = ", ".join(dict.fromkeys(self.link(r["tgt_id"]) for r in parents if r["tgt_id"] in self.entities))
        out.append(f"**Type:** {t.label}" + (f" · **Part of:** {part_of}" if part_of else "") + "\n")
        aliases = [a for a in self.aliases.get(eid, []) if a != e["name"]]
        if aliases:
            out.append("**Also written as:** " + ", ".join(aliases) + "\n")

        out.append("## Mentioned in\n")
        if mentions:
            by_note: dict[str, list[dict]] = defaultdict(list)
            for r in mentions:
                by_note[r["src_id"]].append(r)
            for nid, rs in sorted(by_note.items(), key=lambda kv: self.entities[kv[0]]["name"].casefold()):
                kind = "about" if any(r["type"] == "about" for r in rs) else "mentions"
                ev = next((r["evidence"] for r in rs if r["evidence"]), None)
                out.append(f"- {self.link(nid)}" + (" *(main subject)*" if kind == "about" else "") + _quote(ev))
            out.append("")
        else:
            out.append("_No current mentions. Kept because entities are never deleted automatically._\n")

        if children:
            out.append(f"## Includes\n")
            for r in sorted(children, key=lambda r: self.entities[r["src_id"]]["name"].casefold()):
                ct = ENTITY_TYPES.get(self.entities[r["src_id"]]["type"])
                out.append(f"- {self.link(r['src_id'])}" + (f" ({ct.label.lower()})" if ct else ""))
            out.append("")

        if related:
            out.append("## Related\n")
            for r in related:
                other = r["tgt_id"] if r["src_id"] == eid else r["src_id"]
                if other not in self.entities:
                    continue
                label = r["label"] or "related to"
                arrow = label if r["src_id"] == eid else f"{label} (inverse)"
                out.append(f"- {self.link(other)} — {arrow}{_quote(r['evidence'])}")
            out.append("")
        return "\n".join(out).rstrip() + "\n"

    def note_page(self, e: dict, kind: str) -> str:
        """Reflection / connection page for a source note (links only; never the note's content)."""
        eid = e["id"]
        out = [self.frontmatter(e, kind), f"# {e['name']}\n", BANNER]
        out.append(f"**Source note:** {self.link(eid)}\n")
        if kind == "reflection":
            out.append(f"**Collection:** {self.link(collection_id('Personal Thinking'))}\n")
        ents = [r for r in self.rels if r["src_id"] == eid and r["type"] in ("mentions", "about")]
        if ents:
            out.append("## Mentions\n")
            out += [f"- {self.link(r['tgt_id'])}" for r in ents if r["tgt_id"] in self.entities]
            out.append("")
        links = [r for r in self.rels if r["type"] in ("references", "related_to") and eid in (r["src_id"], r["tgt_id"])
                 and self.entities.get(r["tgt_id" if r["src_id"] == eid else "src_id"], {}).get("type") == NOTE_TYPE]
        if links:
            out.append("## Connected notes\n")
            for r in links:
                other = r["tgt_id"] if r["src_id"] == eid else r["src_id"]
                verb = REL_LABEL[r["type"]] if r["src_id"] == eid else f"{REL_LABEL[r['type']]} (from)"
                p = self.paths.get(other)
                target = f" · [[{self.gen}/{p}|connections]]" if p else ""
                out.append(f"- {self.link(other)} — {verb}{_quote(r['evidence'] or r['label'])}{target}")
            out.append("")
        return "\n".join(out).rstrip() + "\n"

    def collection_page(self, name: str) -> str:
        cid = collection_id(name)
        e = self.entities[cid]
        members = [r["src_id"] for r in self.rels if r["tgt_id"] == cid and r["type"] == "belongs_to"
                   and r["src_id"] in self.entities]
        out = [self.frontmatter(e, "collection"), f"# {name}\n", BANNER]
        if not members:
            out.append("_Nothing here yet._\n")
        groups: dict[str, list[str]] = defaultdict(list)
        for m in members:
            me = self.entities[m]
            label = ENTITY_TYPES[me["type"]].plural_label if me["type"] in ENTITY_TYPES else "Reflections"
            groups[label].append(m)
        for label, ids in sorted(groups.items()):
            out.append(f"## {label}\n")
            for m in sorted(set(ids), key=lambda i: self.entities[i]["name"].casefold()):
                if self.entities[m]["type"] == NOTE_TYPE:
                    out.append(f"- [[{self.gen}/{self.paths[m]}|{_disp(self.entities[m]['name'])}]]" if m in self.paths
                               else f"- {self.link(m)}")
                    continue
                n = sum(1 for r in self.rels if r["tgt_id"] == m and r["type"] in ("mentions", "about"))
                out.append(f"- {self.link(m)}" + (f" · {n} mention{'s' if n != 1 else ''}" if n else ""))
                for r in self.rels:  # one level of nesting: episodes under shows, events under series
                    if r["tgt_id"] == m and r["type"] == "belongs_to" and self.entities.get(r["src_id"], {}).get("type") in ENTITY_TYPES:
                        out.append(f"    - {self.link(r['src_id'])}")
            out.append("")
        return "\n".join(out).rstrip() + "\n"

    def history_page(self) -> str:
        out = ["---", "kb_generated: true", "---", "# Sync history\n", BANNER,
               "| Started | Status | Mirrored | Entities new/reused | Relationships | Errors |",
               "| --- | --- | --- | --- | --- | --- |"]
        for r in self.db.q("SELECT * FROM sync_runs WHERE dry_run=0 AND finished_at IS NOT NULL ORDER BY id DESC LIMIT 50"):
            s = json.loads(r["stats"] or "{}")
            out.append(f"| {r['started_at']} | {r['status']} | {s.get('mirrored', 0)} | "
                       f"{s.get('entities_created', 0)}/{s.get('entities_reused', 0)} | {s.get('relationships', 0)} | "
                       f"{s.get('errors', 0)} |")
        return "\n".join(out) + "\n"

    def build(self) -> dict[str, str]:
        self.assign_paths()
        personal, connected = self.personal_notes(), self.connected_notes()
        for eid, e in self.entities.items():
            if eid not in self.paths:
                continue
            if e["type"] in ENTITY_TYPES:
                self.out[self.paths[eid] + ".md"] = self.entity_page(e)
            elif e["type"] == NOTE_TYPE:
                self.out[self.paths[eid] + ".md"] = self.note_page(e, "reflection" if eid in personal else "connections")
        for name in COLLECTIONS:
            self.out[self.paths[collection_id(name)] + ".md"] = self.collection_page(name)
        ents = [{"id": e["id"], "type": e["type"], "name": e["name"], "aliases": self.aliases.get(e["id"], []),
                 "page": f"{self.gen}/{self.paths[e['id']]}.md" if e["id"] in self.paths else None,
                 "note_id": e["note_id"]} for e in sorted(self.entities.values(), key=lambda e: e["id"])]
        rels = [{k: r[k] for k in ("src_id", "tgt_id", "type", "label", "evidence", "note_id", "confidence", "origin",
                                   "status")} for r in self.rels]
        self.out["Index/entities.json"] = json.dumps(ents, indent=2, ensure_ascii=False) + "\n"
        self.out["Index/relationships.json"] = json.dumps(rels, indent=2, ensure_ascii=False) + "\n"
        self.out["Logs/Sync history.md"] = self.history_page()
        return self.out


def render_all(db: Database, cfg: AppConfig) -> RenderStats:
    r = Renderer(db, cfg)
    desired = r.build()
    stats = RenderStats()
    manifest: dict[str, str] = json.loads(db.scalar("SELECT value FROM meta WHERE key='render_manifest'") or "{}")
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    root = cfg.generated_root()

    def backup(rel: str) -> None:
        r.writer.write_bytes(f"Logs/backups/{stamp}/{rel}", (root / rel).read_bytes())
        stats.backed_up += 1

    new_manifest: dict[str, str] = {}
    for rel, content in desired.items():
        h = sha256_text(content)
        disk = file_sha256(root / rel)
        if disk == h:
            stats.unchanged += 1
        else:
            if disk is not None and manifest.get(rel) != disk:
                backup(rel)  # someone edited a generated page; keep their copy
            r.writer.write_text(rel, content)
            stats.written += 1
        new_manifest[rel] = h
    for rel, old_hash in manifest.items():
        if rel in desired:
            continue
        disk = file_sha256(root / rel)
        if disk is None:
            continue
        if disk != old_hash:
            backup(rel)
        r.writer.delete(rel)
        stats.removed += 1
    with db.tx() as c:
        c.execute("INSERT OR REPLACE INTO meta(key, value) VALUES ('render_manifest', ?)", (json.dumps(new_manifest),))
        for eid, p in r.paths.items():
            c.execute("UPDATE entities SET page_path=? WHERE id=?", (f"{cfg.generated_dir}/{p}.md", eid))
    return stats
